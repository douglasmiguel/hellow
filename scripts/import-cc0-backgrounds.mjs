/**
 * Builds the locally bundled CC0 background expansion from Wikimedia Commons.
 * Run with `node scripts/import-cc0-backgrounds.mjs` when refreshing the set.
 */
import { access, mkdir, rm, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";

const commonsApi = "https://commons.wikimedia.org/w/api.php";
const targetCount = 80;
const sourceCategory = "Category:Images from Unsplash";
const backgroundDir = new URL("../public/backgrounds/", import.meta.url);
const thumbnailDir = new URL("../public/backgrounds/thumbs/", import.meta.url);
const temporaryDir = new URL("../.tmp-cc0-backgrounds/", import.meta.url);

function apiUrl(params) {
  const url = new URL(commonsApi);
  url.search = new URLSearchParams({ format: "json", origin: "*", ...params });
  return url;
}

function plainText(value = "") {
  return value
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();
}

function sourceUrl(title) {
  return `https://commons.wikimedia.org/wiki/${encodeURIComponent(title.replace(/ /g, "_"))}`;
}

function run(command, args) {
  const result = spawnSync(command, args, { stdio: "inherit" });
  if (result.status !== 0) throw new Error(`${command} failed`);
}

async function getCandidatePages() {
  const pages = new Map();
  let continuation = {};

  for (let request = 0; request < 20; request += 1) {
    const response = await fetch(
      apiUrl({
        action: "query",
        generator: "categorymembers",
        gcmtitle: sourceCategory,
        gcmtype: "file",
        gcmlimit: "500",
        prop: "imageinfo",
        iiprop: "url|mime|size|extmetadata",
        iiurlwidth: "1600",
        ...continuation,
      }),
      { headers: { "User-Agent": "Hellow background importer/1.0" } },
    );
    if (!response.ok) throw new Error(`Wikimedia Commons API returned ${response.status}.`);
    const data = await response.json();
    for (const page of Object.values(data.query?.pages ?? {})) {
      if (page.imageinfo?.[0]) pages.set(page.title, page);
    }
    continuation = data.continue ?? {};
    if (pages.size >= 100 || !Object.keys(continuation).length) break;
    await new Promise((resolve) => setTimeout(resolve, 750));
  }

  return [...pages.values()]
    .map((page) => ({ ...page, image: page.imageinfo?.[0] }))
    .filter(
      (page) =>
        page.image?.mime === "image/jpeg" &&
        page.image?.thumburl &&
        page.image.width >= 1600 &&
        page.image.height >= 900 &&
        page.image.width / page.image.height >= 1.25,
    );
}

async function main() {
  const candidates = await getCandidatePages();
  if (candidates.length < targetCount) {
    throw new Error(`Only found ${candidates.length} suitable CC0 images.`);
  }

  await mkdir(backgroundDir, { recursive: true });
  await mkdir(thumbnailDir, { recursive: true });
  await mkdir(temporaryDir, { recursive: true });

  const additions = [];
  for (const page of candidates) {
    if (additions.length === targetCount) break;
    const id = `cc0-${String(additions.length + 1).padStart(2, "0")}`;
    const input = new URL(`${id}.jpg`, temporaryDir);
    const fullImage = new URL(`${id}.webp`, backgroundDir);
    const thumbnail = new URL(`${id}.webp`, thumbnailDir);
    try {
      await access(input);
    } catch {
      try {
        run("curl", [
          "-sS",
          "-L",
          "--fail",
          "--retry",
          "3",
          "--retry-delay",
          "1",
          "-A",
          "Hellow background importer/1.0",
          page.image.thumburl,
          "-o",
          input.pathname,
        ]);
      } catch {
        console.warn(`Skipped ${page.title}: image host did not respond.`);
        continue;
      }
    }
    run("cwebp", ["-quiet", "-q", "80", input.pathname, "-o", fullImage.pathname]);
    run("cwebp", ["-quiet", "-q", "70", "-resize", "480", "0", input.pathname, "-o", thumbnail.pathname]);

    const name = page.title.replace(/^File:/, "").replace(/\.[^.]+$/, "").replace(/_/g, " ");
    const author = plainText(page.image.extmetadata?.Artist?.value) || "Unsplash contributor";
    additions.push({
      id,
      name,
      file: `backgrounds/${id}.webp`,
      thumbnail: `backgrounds/thumbs/${id}.webp`,
      author,
      source: sourceUrl(page.title),
      color: "#183440",
      creditTitle: page.title.replace(/^File:/, ""),
    });
  }

  const module = `// Generated by scripts/import-cc0-backgrounds.mjs. Do not edit by hand.\nimport type { Photo } from "./photos";\n\nexport const additionalPhotos: Photo[] = ${JSON.stringify(
    additions.map(({ creditTitle, ...photo }) => photo),
    null,
    2,
  )};\n`;
  await writeFile(new URL("../src/photo-additions.generated.ts", import.meta.url), module);

  const credits = additions
    .map(
      ({ id, creditTitle, author, source }) =>
        `| \`${id}.webp\` | [${creditTitle}](${source}) | ${author.replace(/\|/g, "\\|")} |`,
    )
    .join("\n");
  await writeFile(
    new URL("../PHOTO_CREDITS.generated.md", import.meta.url),
    `## Additional CC0 backgrounds\n\n| File | Photo | Creator |\n| --- | --- | --- |\n${credits}\n`,
  );

  await rm(temporaryDir, { recursive: true, force: true });
  console.log(`Imported ${additions.length} CC0 backgrounds.`);
}

await main();
